import {chromium} from '@playwright/test';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {mkdirSync,mkdtempSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {execFileSync} from 'node:child_process';

const here=dirname(fileURLToPath(import.meta.url));
const images=process.env.PAPERLOOP_TEST_WORK||mkdtempSync(resolve(tmpdir(),'paperloop-browser-'));
mkdirSync(images,{recursive:true});
const sample=resolve(images,'browser-two-page.pdf');
const localPython=resolve(here,'../.venv',process.platform==='win32'?'Scripts/python.exe':'bin/python');
execFileSync(process.env.PAPERLOOP_PYTHON||(existsSync(localPython)?localPython:'python'),[resolve(here,'make_fixture.py'),sample]);
const edge='C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser=await chromium.launch({headless:true,executablePath:process.env.PAPERLOOP_BROWSER_EXECUTABLE||(existsSync(edge)?edge:undefined)});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto(process.env.PAPERLOOP_BASE_URL||'http://127.0.0.1:8765',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:/把论文读懂/}).waitFor();
  await page.screenshot({path:resolve(images,'paperloop-home.png'),fullPage:true});
  await page.locator('input[type=file]').setInputFiles(sample);
  await page.locator('.reader-title h1').waitFor({timeout:20000});
  await page.locator('.translation-block').first().waitFor({timeout:20000});
  await page.locator('.page-sheet canvas').waitFor({timeout:20000});
  await page.locator('.page-loading').waitFor({state:'hidden',timeout:20000});
  await page.locator('.translation-block').first().click();
  await page.locator('.pdf-highlight').waitFor({timeout:5000});
  await page.locator('.page-loading').waitFor({state:'hidden',timeout:20000});
  await page.screenshot({path:resolve(images,'paperloop-reader.png'),fullPage:true});
  await page.getByTitle('下一页',{exact:true}).click();
  await page.locator('.pdf-highlight').waitFor({state:'hidden'});
  if(await page.locator('.translation-block.chosen').count())throw new Error('Previous-page selection was retained');
  await page.getByRole('button',{name:'提问',exact:true}).click();
  if(await page.getByLabel('提问范围').inputValue()!=='page')throw new Error('Question scope did not follow page navigation');
  await page.getByRole('button',{name:/笔记/}).first().click();
  const toast=page.locator('.toast button');
  if(await toast.isVisible())await toast.click();
  await page.getByPlaceholder('记录你的理解、疑问或灵感…').fill('浏览器测试：值得继续阅读的方法。');
  const saved=page.waitForResponse(r=>r.url().endsWith('/notes')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'保存笔记'}).click();
  const note=await (await saved).json();
  if(note.page!==2||note.block_id!==null)throw new Error('Note retained a previous-page block');
  await page.reload({waitUntil:'networkidle'});
  await page.locator('.paper-card').filter({hasText:'PaperLoop Browser Study'}).first().click();
  await page.getByRole('button',{name:/笔记/}).first().click();
  await page.getByText('浏览器测试：值得继续阅读的方法。').first().waitFor();
  if(errors.length)throw new Error('Browser errors: '+errors.join(' | '));
  console.log('Browser flow passed. Screenshots:',resolve(images,'paperloop-home.png'),resolve(images,'paperloop-reader.png'));
}finally{await browser.close();}
