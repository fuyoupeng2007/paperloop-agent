import {chromium} from '../outputs/paper-reader/node_modules/@playwright/test/index.mjs';
const browser=await chromium.launch({headless:true,executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe'});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto('http://127.0.0.1:8766/',{waitUntil:'networkidle'});
  await page.locator('.paper-card').filter({hasText:'MonkeyOCR'}).first().click();
  await page.locator('.page-loading').waitFor({state:'hidden',timeout:20000});
  const figure=page.locator('.pdf-object-badge').filter({hasText:'图 1'}).first();
  await figure.waitFor({timeout:10000});
  const zone=await page.locator('.pdf-object-zone').first().boundingBox();
  if(!zone)throw new Error('Figure hit region missing');
  const center={x:zone.x+zone.width/2,y:zone.y+zone.height/2};
  await page.mouse.click(center.x,center.y);
  await page.locator('.conversation-context').filter({hasText:'图 1'}).waitFor();
  await page.mouse.dblclick(center.x,center.y);
  await page.getByRole('dialog',{name:/图 1.*放大查看/}).waitFor();
  await page.waitForFunction(()=>{const c=document.querySelector('.figure-viewer-stage canvas');return c instanceof HTMLCanvasElement&&c.width>100&&c.height>100;});
  const pixels=await page.locator('.figure-viewer-stage canvas').evaluate(c=>{const canvas=c;const ctx=canvas.getContext('2d');let colored=0;for(let y=0;y<canvas.height;y+=20)for(let x=0;x<canvas.width;x+=20){const p=ctx.getImageData(x,y,1,1).data;if(p[3]>0&&(p[0]<245||p[1]<245||p[2]<245))colored++;}return colored;});
  if(pixels<10)throw new Error('Cropped figure canvas appears blank');
  const initial=await page.locator('.figure-viewer-head .tools span').innerText();
  await page.locator('.figure-viewer-stage').hover();await page.mouse.wheel(0,-500);
  await page.waitForTimeout(100);
  const changed=await page.locator('.figure-viewer-head .tools span').innerText();
  if(initial===changed)throw new Error('Figure wheel zoom did not change');
  if(!await page.locator('.assistant-panel').isVisible())throw new Error('Assistant not visible beside figure');
  await page.getByRole('button',{name:'关闭',exact:true}).last().click();
  await page.locator('.figure-viewer').waitFor({state:'hidden'});
  const textSpan=page.locator('.page-sheet .textLayer span').filter({hasText:/MonkeyOCR/}).first();
  await textSpan.evaluate(el=>{const node=el.firstChild;if(!node)return;const range=document.createRange();range.setStart(node,0);range.setEnd(node,Math.min(8,node.textContent?.length||0));const selection=window.getSelection();selection?.removeAllRanges();selection?.addRange(range);const r=range.getBoundingClientRect();el.closest('.page-sheet')?.dispatchEvent(new MouseEvent('mouseup',{bubbles:true,clientX:r.left+2,clientY:r.top+2}));});
  await page.getByRole('toolbar',{name:'选中文字操作'}).waitFor();
  await page.getByRole('toolbar',{name:'选中文字操作'}).getByRole('button',{name:'提问'}).click();
  await page.locator('.conversation-context').filter({hasText:'选中文字'}).waitFor();
  await page.getByTitle('切换连续阅读').click();
  if(await page.locator('.paper-page-wrap').count()<2)throw new Error('Continuous pages did not mount');
  await page.locator('.pdf-scroll').evaluate(el=>{const target=el.querySelector('[data-pdf-page="2"]');if(target instanceof HTMLElement)el.scrollTop=target.offsetTop-el.offsetTop+5;});
  await page.waitForFunction(()=>document.querySelector('select[aria-label="当前页"]')?.value==='2',{timeout:5000});
  if(errors.length)throw new Error(errors.join(' | '));
  console.log('reader-ui-check passed', {figureInitial:initial,figureZoom:changed,continuousPages:await page.locator('.paper-page-wrap').count()});
}finally{await browser.close();}
